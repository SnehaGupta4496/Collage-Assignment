const facultySelect = document.getElementById("facultySelect");
const facultySearch = document.getElementById("facultySearch");
const searchResults = document.getElementById("searchResults");
const profileSection = document.getElementById("profileSection");
const emptyState = document.getElementById("emptyState");
const themeToggle = document.getElementById("themeToggle");

function populateDropdown() {
    facultyData.forEach((faculty, index) => {
        const option = document.createElement("option");
        option.value = index;
        option.textContent = faculty.name;
        facultySelect.appendChild(option);
    });
}

function displayFaculty(index) {
    const faculty = facultyData[index];

    if (!faculty) return;

    document.getElementById("facultyName").textContent = faculty.name;

    document.getElementById("facultyDesignation").textContent =
        faculty.designation;

    document.getElementById("facultyQualification").textContent =
        faculty.qualification;

    const email = document.getElementById("facultyEmail");

    email.textContent = faculty.email;
    email.href = "mailto:" + faculty.email;

    const photo = document.getElementById("facultyPhoto");

    photo.src = faculty.photo;
    photo.alt = faculty.name;

    const subjects =
        document.getElementById("facultySubjects");

    subjects.innerHTML = "";

    faculty.subjects.forEach(subject => {
        const li = document.createElement("li");
        li.textContent = subject;
        subjects.appendChild(li);
    });

    const research =
        document.getElementById("facultyResearch");

    research.innerHTML = "";

    faculty.researchAreas.forEach(area => {
        const tag = document.createElement("span");

        tag.className = "research-tag";
        tag.textContent = area;

        research.appendChild(tag);
    });

    profileSection.classList.remove("hidden");
    emptyState.style.display = "none";

    profileSection.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });
}

facultySelect.addEventListener("change", function () {

    if (this.value === "") {
        profileSection.classList.add("hidden");
        emptyState.style.display = "block";
        return;
    }

    displayFaculty(Number(this.value));
});

facultySearch.addEventListener("input", function () {

    const searchText =
        this.value.trim().toLowerCase();

    searchResults.innerHTML = "";

    if (searchText === "") {
        searchResults.style.display = "none";
        return;
    }

    const matches = facultyData.filter(faculty =>
        faculty.name.toLowerCase().includes(searchText)
    );

    if (matches.length === 0) {

        searchResults.innerHTML =
            `<div class="search-result-item">
                No faculty member found.
            </div>`;

        searchResults.style.display = "block";
        return;
    }

    matches.forEach(faculty => {

        const index = facultyData.indexOf(faculty);

        const result =
            document.createElement("div");

        result.className = "search-result-item";
        result.textContent = faculty.name;

        result.addEventListener("click", function () {

            facultySearch.value = faculty.name;
            facultySelect.value = index;
            searchResults.style.display = "none";

            displayFaculty(index);
        });

        searchResults.appendChild(result);
    });

    searchResults.style.display = "block";
});

themeToggle.addEventListener("click", function () {

    document.body.classList.toggle("dark");

    if (document.body.classList.contains("dark")) {
        themeToggle.textContent = "☀️ Light Mode";
    } else {
        themeToggle.textContent = "🌙 Dark Mode";
    }
});

populateDropdown();